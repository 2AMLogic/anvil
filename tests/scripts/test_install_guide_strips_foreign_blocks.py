"""Regression tests: installed ``.anvil/CLAUDE.md`` omits foreign marker blocks.

Issue #1535. ``write_guide()`` in ``scripts/install-anvil.sh`` used to ``cat``
the Anvil source ``CLAUDE.md`` verbatim into the consumer's
``.anvil/CLAUDE.md``. That source carries ``<!-- BEGIN LOOM ORCHESTRATION -->``
and ``<!-- BEGIN REPO-SKILLS -->`` blocks written by *other* tools' installers
into the Anvil repo; they describe that repo, not the consumer.

``write_guide`` now filters every ``<!-- BEGIN X --> ... <!-- END X -->`` block
generically. These tests drive ``write_guide`` directly (it is extracted from
the installer, so a synthetic source ``CLAUDE.md`` can be supplied) plus one
end-to-end run against the real source file. Distinct filename per the #58
packaging convention.
"""

from __future__ import annotations

import re
import subprocess
from pathlib import Path

from anvil.lib.testing import assert_ok as _assert_ok

REPO_ROOT = Path(__file__).resolve().parents[2]
INSTALLER = REPO_ROOT / "scripts" / "install-anvil.sh"

MARKER_RE = re.compile(r"<!-- (BEGIN|END) [^>]* -->")


def _write_guide(tmp_path: Path, source_text: str) -> tuple[str, str]:
    """Run the installer's ``write_guide`` on ``source_text``.

    Returns ``(installed guide text, stderr)``.
    """

    src = tmp_path / "SRC_CLAUDE.md"
    src.write_bytes(source_text.encode())
    target = tmp_path / "target"
    script = (
        f"source <(sed -n '/^strip_foreign_marker_blocks()/,/^}}/p;"
        f"/^write_guide()/,/^}}/p' '{INSTALLER}')\n"
        f"write_guide '{target}' 1.2.3 2026-01-01 '{src}' '{target}/.anvil/CLAUDE.md'\n"
    )
    result = subprocess.run(
        ["bash", "-c", script], capture_output=True, text=True, cwd=tmp_path
    )
    assert result.returncode == 0, result.stderr
    return (target / ".anvil" / "CLAUDE.md").read_text(), result.stderr


HEADER = (
    "<!-- Generated by install-anvil.sh -->\n"
    "<!-- Anvil Version: 1.2.3 -->\n"
    "<!-- Install Date: 2026-01-01 -->\n"
    "\n"
)


def test_blocks_removed_and_surrounding_prose_kept(tmp_path: Path) -> None:
    source = (
        "# Guide\n"
        "intro line\n"
        "\n"
        "## Status of work<!-- BEGIN LOOM ORCHESTRATION -->\n"
        "LOOM-ONLY-BODY secret\n"
        "<!-- END LOOM ORCHESTRATION -->\n"
        "<!-- BEGIN REPO-SKILLS -->\n"
        "REPO-ONLY-BODY secret\n"
        "<!-- END REPO-SKILLS -->\n"
        "\n"
        "## After\n"
        "tail prose\n"
    )
    guide, stderr = _write_guide(tmp_path, source)

    assert not MARKER_RE.search(guide)
    assert "LOOM-ONLY-BODY" not in guide
    assert "REPO-ONLY-BODY" not in guide
    # One info line per stripped block, naming it and its source line span.
    assert stderr.splitlines() == [
        "info: stripped foreign block 'LOOM ORCHESTRATION' (SRC_CLAUDE.md:4-6)",
        "info: stripped foreign block 'REPO-SKILLS' (SRC_CLAUDE.md:7-9)",
    ]
    # Generated-by header unchanged; heading sharing the marker line survives.
    assert (
        guide
        == HEADER + "# Guide\nintro line\n\n## Status of work\n\n## After\ntail prose\n"
    )


def test_unrelated_block_names_are_also_stripped(tmp_path: Path) -> None:
    source = (
        "a\n<!-- BEGIN SOME-FUTURE-TOOL -->\nbody\n<!-- END SOME-FUTURE-TOOL -->\nb\n"
    )
    guide, stderr = _write_guide(tmp_path, source)
    assert guide == HEADER + "a\nb\n"
    assert stderr.splitlines() == [
        "info: stripped foreign block 'SOME-FUTURE-TOOL' (SRC_CLAUDE.md:2-4)"
    ]


def test_text_after_end_marker_is_kept(tmp_path: Path) -> None:
    source = "x <!-- BEGIN T -->\nbody\n<!-- END T --> y\nz\n"
    guide, stderr = _write_guide(tmp_path, source)
    assert guide == HEADER + "x  y\nz\n"
    assert stderr.splitlines() == [
        "info: stripped foreign block 'T' (SRC_CLAUDE.md:1-3)"
    ]


def test_unterminated_begin_passes_through_with_warning(tmp_path: Path) -> None:
    source = "before\nhead <!-- BEGIN OPEN -->\nstill here\nlast\n"
    guide, stderr = _write_guide(tmp_path, source)
    assert guide == HEADER + source
    assert "unterminated" in stderr
    assert "stripped foreign block" not in stderr


def test_source_without_blocks_is_byte_identical(tmp_path: Path) -> None:
    # No trailing newline on purpose: the no-block path must be plain `cat`.
    source = "# Guide\n\n\nno blocks here <!-- inline comment -->\nlast line"
    guide, stderr = _write_guide(tmp_path, source)
    assert guide == HEADER + source
    assert stderr == ""


def test_prose_mention_of_begin_marker_logs_oversized_span(tmp_path: Path) -> None:
    # The match is positional: a prose mention of a BEGIN marker pairs with the
    # next real END marker and swallows everything between (#1537). The strip
    # itself is unchanged, but the span in the info line makes it visible.
    filler = "".join(f"guide line {i}\n" for i in range(1, 41))
    source = (
        "# Guide\n"
        "Mentioning <!-- BEGIN LOOM ORCHESTRATION --> inline in prose.\n"
        + filler
        + "<!-- BEGIN LOOM ORCHESTRATION -->\nreal body\n"
        "<!-- END LOOM ORCHESTRATION -->\n"
        "tail\n"
    )
    guide, stderr = _write_guide(tmp_path, source)
    lines = stderr.splitlines()
    assert lines == [
        "info: stripped foreign block 'LOOM ORCHESTRATION' (SRC_CLAUDE.md:2-45)"
    ]
    # The unintended deletion is real: the filler is gone from the guide.
    assert "guide line 1\n" not in guide
    assert guide == HEADER + "# Guide\nMentioning \ntail\n"


def test_real_installer_run_ships_no_foreign_blocks(tmp_path: Path) -> None:
    target = tmp_path / "consumer"
    target.mkdir()
    result = subprocess.run(
        ["bash", str(INSTALLER), "-y", "--no-sync", "--skills=memo", str(target)],
        capture_output=True,
        text=True,
        cwd=REPO_ROOT,
    )
    _assert_ok(result)

    guide = (target / ".anvil" / "CLAUDE.md").read_text()
    source = (REPO_ROOT / "CLAUDE.md").read_text()
    # Exactly the two known blocks are stripped from the real source -- an
    # unintended extra strip (e.g. a prose-mention pairing) changes this list.
    stripped = re.findall(
        r"^info: stripped foreign block '([^']*)' \(CLAUDE\.md:(\d+)-(\d+)\)$",
        result.stderr + result.stdout,
        flags=re.MULTILINE,
    )
    assert [name for name, _, _ in stripped] == ["LOOM ORCHESTRATION", "REPO-SKILLS"]
    for _, start, end in stripped:
        assert int(end) - int(start) < 20  # real blocks are small
    assert not MARKER_RE.search(guide)
    assert "LOOM ORCHESTRATION" not in guide
    assert "REPO-SKILLS" not in guide
    assert "## Status of work\n" in guide
    # The source file itself is untouched and still carries its blocks.
    assert "<!-- BEGIN LOOM ORCHESTRATION -->" in source
